package protocol

type Domain string

const (
	DomainProject   Domain = "project"
	DomainDocument  Domain = "document"
	DomainSchematic Domain = "schematic"
	DomainPcb       Domain = "pcb"
	DomainBoard     Domain = "board"
	DomainArtifact  Domain = "artifact"
	DomainSystem    Domain = "system"
	DomainDebug     Domain = "debug"
	DomainLibrary   Domain = "library"
)

type ActionSpec struct {
	Name         string   `json:"name"`
	Domain       Domain   `json:"domain"`
	Phase        int      `json:"phase"`
	Mutates      bool     `json:"mutates"`
	NeedsWindow  bool     `json:"needsWindow"`
	NeedsConfirm bool     `json:"needsConfirm"`
	Description  string   `json:"description"`
	Inputs       []string `json:"inputs,omitempty"`
	Outputs      []string `json:"outputs,omitempty"`
	VerifyWith   []string `json:"verifyWith,omitempty"`

	// RequiresGate names a workflow gate that must pass before the daemon
	// dispatches this action ("routing" = outline_confirmed + pre_route_passed
	// in the project's persisted stage state; see internal/workflow). A caller
	// can override with an explicit, audited forceReason on the request.
	RequiresGate string `json:"requiresGate,omitempty"`
	// InvalidatesStage is the EARLIEST workflow stage this mutation invalidates
	// on success (that stage and everything downstream is cleared) — a moved
	// part or a redrawn outline can never leave a stale confirmation standing.
	InvalidatesStage string `json:"invalidatesStage,omitempty"`
}

