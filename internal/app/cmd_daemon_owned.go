var daemonOwnerIDPattern = regexp.MustCompile(`(?i)^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// Owned services have no detached launcher, shared PID file or port replacement.
// The parent's pipe is the lifetime authority, including when the parent crashes.
func newDaemonServeOwnedCmd(stdout io.Writer) *cobra.Command {
	var port int
	var ownerID string
	var autosaveDebounce time.Duration
	c := &cobra.Command{
		Use: "serve-owned", Short: "Serve a fixed loopback port until the owning application's stdin pipe closes",
		Long:    "Run directly in the foreground on 127.0.0.1. Keep stdin connected to an owning application's pipe; EOF or a read error gracefully shuts down this service, including after parent exit/crash. Never probes, replaces or reuses an occupied port, writes the shared PID file, or syncs Skills. Health exposes lifecycle mode/ownerId/instanceId. These are public identity fields, not credentials. Save and close editor documents before ending the pipe; service shutdown is not proof that an editor action completed.",
		Example: "  easyeda daemon serve-owned --port 60833 --owner-id 75d0f0d8-9dd4-4c11-a4f7-606fa1a7b6cd\n  # Spawn with an open stdin pipe; closing that pipe ends only this child.",
		Args:    cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if port < 1024 || port > 65535 || !daemonOwnerIDPattern.MatchString(ownerID) || autosaveDebounce < 0 {
				return fmt.Errorf("explicit --port (1024-65535), UUID --owner-id and nonnegative --autosave-debounce are required")
			}
			var nonce [16]byte
			if _, err := rand.Read(nonce[:]); err != nil {
				return fmt.Errorf("create daemon instance identity: %w", err)
			}
			ctx, stop := signal.NotifyContext(cmd.Context(), os.Interrupt, syscall.SIGTERM)
			defer stop()
			return runOwnedDaemon(ctx, cmd.InOrStdin(), daemon.Options{
				Host: "127.0.0.1", PortStart: port, PortEnd: port, Version: version.Version,
				AutosaveDebounce: autosaveDebounce,
				Lifecycle:        &daemon.Lifecycle{Mode: "stdin", OwnerID: ownerID, InstanceID: hex.EncodeToString(nonce[:])},
			}, stdout)
		},
	}
	c.Flags().IntVar(&port, "port", 0, "explicit fixed loopback port; an occupied port fails without affecting its owner")
	c.Flags().StringVar(&ownerID, "owner-id", "", "fresh UUID generated by the owning application for this direct child")
	c.Flags().DurationVar(&autosaveDebounce, "autosave-debounce", 3*time.Second, "autosave after edits quiesce (0 disables); service exit is not document save confirmation")
	return c
}

func runOwnedDaemon(parent context.Context, input io.Reader, options daemon.Options, log io.Writer) error {
	ctx, cancel := context.WithCancel(parent)
	defer cancel()
	ended := make(chan error, 1)
	go func() {
		_, err := io.Copy(io.Discard, input)
		ended <- err
		cancel()
	}()
	err := daemon.New(options).Run(ctx, log)
	if err != nil {
		return err
	}
	select {
	case readErr := <-ended:
		if readErr != nil {
			return fmt.Errorf("owner stdin failed; daemon shut down: %w", readErr)
		}
	default: // A signal or command cancellation ended the service first.
	}
	return nil
}
